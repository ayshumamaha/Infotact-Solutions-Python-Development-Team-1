logger = logging.getLogger("meshweaver.kademlia")


# ============================================================
# KADEMLIA PARAMETERS
# ============================================================

ID_BITS = 160
K = 20
ALPHA = 3

RPC_TIMEOUT = 3.0
REFRESH_INTERVAL = 60.0


# ============================================================
# MESSAGE TYPES
# ============================================================

KADEMLIA_PING = "KADEMLIA_PING"
KADEMLIA_PONG = "KADEMLIA_PONG"

