# GOSSIP PROTOCOL
# ============================================================

class GossipProtocol:

    def __init__(
        self,
        node_id,
        fanout=DEFAULT_FANOUT,
        interval=GOSSIP_INTERVAL
    ):

        self.node_id = str(
            node_id
        )

        self.fanout = max(
            1,
            int(fanout)
        )

        self.interval = max(
            0.1,
            float(interval)
        )

        # ----------------------------------------------------
        # Known neighbours
        #
        # node_id -> peer object / address
        # ----------------------------------------------------

        self.neighbours = {}

        # ----------------------------------------------------
        # Latest resource information
        #
        # node_id -> information
        # ----------------------------------------------------

        self.peer_loads = {}

        # ----------------------------------------------------
        # Duplicate protection
        # ----------------------------------------------------

        self.seen_messages = {}

        # ----------------------------------------------------
        # Background task
        # ----------------------------------------------------

        self.running = False

        self.gossip_task = None

    # ========================================================
    # ADD NEIGHBOUR
    # ========================================================

    def add_neighbour(
        self,
        node_id,
        peer=None
    ):

        node_id = str(
            node_id
        )

        if node_id == self.node_id:
            return False

        self.neighbours[
            node_id
        ] = peer

        return True

    # ========================================================
    # REMOVE NEIGHBOUR
    # ========================================================

    def remove_neighbour(
        self,
        node_id
    ):

        self.neighbours.pop(
            str(node_id),
            None
        )

    # ========================================================
    # GET NEIGHBOURS
    # ========================================================

    def get_neighbours(self):

        return list(
            self.neighbours.keys()
        )

    # ========================================================
    # CREATE MESSAGE
    # ========================================================

    def create_message(self):

        load = get_cpu_ram()

        return GossipMessage(
            sender_id=self.node_id,

            cpu_percent=load[
                "cpu_percent"
            ],

            ram_percent=load[
                "ram_percent"
            ]
        )

    # ========================================================
    # RECEIVE MESSAGE
    # ========================================================

    def receive(
        self,
        message
    ):
        """
        Process an incoming gossip message.

        Returns True when the message is accepted.
        """

        # ----------------------------------------------------
        # Convert dictionary if necessary.
        # ----------------------------------------------------

        if isinstance(
            message,
            dict
        ):

            try:

                message = (
                    GossipMessage
                    .from_dict(message)
                )

            except Exception:

                return False

        if not isinstance(
            message,
            GossipMessage
        ):

            return False

        # ----------------------------------------------------
        # Ignore ourselves.
        # ----------------------------------------------------

        if (
            message.sender_id
            == self.node_id
        ):
            return False

        # ----------------------------------------------------
        # Ignore duplicate messages.
        # ----------------------------------------------------

        if (
            message.message_id
            in self.seen_messages
        ):
            return False

        self.seen_messages[
            message.message_id
        ] = time.time()

        # ----------------------------------------------------
        # Validate CPU.
        # ----------------------------------------------------

        try:

            cpu = float(
                message.cpu_percent
            )

            ram = float(
                message.ram_percent
            )

        except (
            TypeError,
            ValueError
        ):

            return False

        # ----------------------------------------------------
        # Keep values within valid range.
        # ----------------------------------------------------

        cpu = max(
            0.0,
            min(100.0, cpu)
        )

        ram = max(
            0.0,
            min(100.0, ram)
        )

        # ----------------------------------------------------
        # Ignore stale information.
        # ----------------------------------------------------

        if (
            time.time()
            - message.timestamp
            > STALE_AFTER
        ):

            return False

        # ----------------------------------------------------
        # Store latest information.
        # ----------------------------------------------------

        old = self.peer_loads.get(
            message.sender_id
        )

        if (
            old is not None
            and message.timestamp
            <= old["timestamp"]
        ):

            return False

        self.peer_loads[
            message.sender_id
        ] = {

            "node_id":
                message.sender_id,

            "cpu_percent":
                cpu,

            "ram_percent":
                ram,

            "timestamp":
                message.timestamp
        }

        return True

    # ========================================================
    # SELECT GOSSIP NEIGHBOURS
    # ========================================================

    def select_neighbours(self):

        peers = list(
            self.neighbours.items()
        )

        random.shuffle(
            peers
        )

        return peers[
            :self.fanout
        ]

    # ========================================================
    # BUILD OUTGOING GOSSIP
    # ========================================================

    def prepare_gossip(self):

        message = self.create_message()

        return [
            (
                node_id,
                peer,
                message
            )

            for node_id, peer
            in self.select_neighbours()
        ]

    # ========================================================
    # START
    # ========================================================

    async def start(
        self,
        send_function=None
    ):
        """
        Start background gossip.

        send_function is optional.

        Later integration can provide:

            async def send_function(peer, message):
                ...

        The module itself does not assume how the common
        MeshWeaver networking layer sends messages.
        """

        if self.running:
            return

        self.running = True

        self.gossip_task = asyncio.create_task(
            self._gossip_loop(
                send_function
            )
        )

    # ========================================================
    # STOP
    # ========================================================

    async def stop(self):

        self.running = False

        if self.gossip_task:

            self.gossip_task.cancel()

            try:

                await self.gossip_task

            except asyncio.CancelledError:
                pass

            self.gossip_task = None

    # ========================================================
    # GOSSIP LOOP
    # ========================================================

    async def _gossip_loop(
        self,
        send_function
    ):

        while self.running:

            try:

                await asyncio.sleep(
                    self.interval
                )

                if not self.running:
                    break

                await self.broadcast(
                    send_function
                )

                self.cleanup()

            except asyncio.CancelledError:

                break

            except Exception:

                # Never terminate the background gossip
                # task because of one bad peer/message.
                continue

    # ========================================================
    # BROADCAST
    # ========================================================

    async def broadcast(
        self,
        send_function=None
    ):

        outgoing = (
            self.prepare_gossip()
        )

        if send_function is None:

            # ------------------------------------------------
            # No networking layer connected yet.
            #
            # The message is still generated correctly.
            # ------------------------------------------------

            return [
                message.to_dict()
                for (
                    node_id,
                    peer,
                    message
                ) in outgoing
            ]

        sent = 0

        for (
            node_id,
            peer,
            message
        ) in outgoing:

            try:

                result = send_function(
                    peer,
                    message
                )

                if asyncio.iscoroutine(
                    result
                ):

                    await result

                sent += 1

            except Exception:

                continue

        return sent

    # ========================================================
    # CLEANUP
    # ========================================================

    def cleanup(self):

        now = time.time()

        # ----------------------------------------------------
        # Remove stale resource data.
        # ----------------------------------------------------

        for node_id, data in list(
            self.peer_loads.items()
        ):

            if (
                now - data["timestamp"]
                > STALE_AFTER
            ):

                self.peer_loads.pop(
                    node_id,
                    None
                )

        # ----------------------------------------------------
        # Remove old message IDs.
        # ----------------------------------------------------

        for message_id, timestamp in list(
            self.seen_messages.items()
        ):

            if (
                now - timestamp
                > 60
            ):

                self.seen_messages.pop(
                    message_id,
                    None
                )

    # ========================================================
    # GET PEER LOAD
    # ========================================================

    def get_peer_load(
        self,
        node_id
    ):

        data = self.peer_loads.get(
            str(node_id)
        )

        if data is None:
            return None

        if (
            time.time()
            - data["timestamp"]
            > STALE_AFTER
        ):

            return None

        return dict(data)

    # ========================================================
    # GET ALL LOADS
    # ========================================================

    def get_all_peer_loads(self):

        self.cleanup()

        return {
            node_id: dict(data)
            for node_id, data
            in self.peer_loads.items()
        }

    # ========================================================
    # LEAST LOADED NODE
    # ========================================================

    def get_least_loaded_peer(
        self,
        metric="cpu_percent"
    ):

        if metric not in (
            "cpu_percent",
            "ram_percent"
        ):

            raise ValueError(
                "metric must be cpu_percent "
                "or ram_percent"
            )

        loads = (
            self.get_all_peer_loads()
        )

        if not loads:
            return None

        return min(
            loads.values(),
            key=lambda data:
                data[metric]
        )

    # ========================================================
    # STATUS
    # ========================================================

    def status(self):

        return {

            "node_id":
                self.node_id,

            "running":
                self.running,

            "interval":
                self.interval,

            "fanout":
                self.fanout,

            "neighbours":
                len(
                    self.neighbours
                ),

            "known_peer_loads":
                len(
                    self.peer_loads
                )
        }


