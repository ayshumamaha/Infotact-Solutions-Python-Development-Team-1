async def gossip_demo():

    print(
        "======================================"
    )

    print(
        " MeshWeaver Gossip Protocol"
    )

    print(
        "======================================"
    )

    # --------------------------------------------------------
    # Create three independent Gossip nodes.
    # --------------------------------------------------------

    node_a = GossipProtocol(
        "node-A"
    )

    node_b = GossipProtocol(
        "node-B"
    )

    node_c = GossipProtocol(
        "node-C"
    )

    # --------------------------------------------------------
    # Connect neighbours.
    # --------------------------------------------------------

    node_a.add_neighbour(
        "node-B"
    )

    node_a.add_neighbour(
        "node-C"
    )

    node_b.add_neighbour(
        "node-A"
    )

    node_b.add_neighbour(
        "node-C"
    )

    node_c.add_neighbour(
        "node-A"
    )

    node_c.add_neighbour(
        "node-B"
    )

    # --------------------------------------------------------
    # Create one gossip message.
    # --------------------------------------------------------

    message = node_a.create_message()

    print(
        "\nNode-A generated:"
    )

    print(
        message.to_dict()
    )

    # --------------------------------------------------------
    # Deliver it to B and C.
    # --------------------------------------------------------

    accepted_b = node_b.receive(
        message
    )

    accepted_c = node_c.receive(
        message
    )

    print(
        "\nNode-B accepted:",
        accepted_b
    )

    print(
        "Node-C accepted:",
        accepted_c
    )

    # --------------------------------------------------------
    # Display received information.
    # --------------------------------------------------------

    print(
        "\nNode-B knows:"
    )

    print(
        node_b.get_all_peer_loads()
    )

    print(
        "\nNode-C knows:"
    )

    print(
        node_c.get_all_peer_loads()
    )

    # --------------------------------------------------------
    # Test duplicate protection.
    # --------------------------------------------------------

    duplicate = node_b.receive(
        message
    )

    print(
        "\nDuplicate accepted:",
        duplicate
    )

    print(
        "\nGossip test completed successfully."
    )


