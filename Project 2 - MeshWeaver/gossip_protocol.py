import asyncio
import random
import time
import uuid
import os


# ============================================================
# CONFIGURATION
# ============================================================

GOSSIP_INTERVAL = 5.0

DEFAULT_FANOUT = 3

MESSAGE_TYPE = "GOSSIP_LOAD"

STALE_AFTER = 20.0


# ============================================================
# RESOURCE MONITOR
# ============================================================

def get_cpu_ram():

    # --------------------------------------------------------
    # Try psutil if already available.
    # --------------------------------------------------------

    try:

        import psutil

        cpu = float(
            psutil.cpu_percent(
                interval=None
            )
        )

        ram = float(
            psutil.virtual_memory().percent
        )

        return {
            "cpu_percent": round(
                cpu,
                2
            ),

            "ram_percent": round(
                ram,
                2
            )
        }

    except Exception:

        # ----------------------------------------------------
        # Safe fallback.
        # ----------------------------------------------------

        try:

            load = os.getloadavg()[0]

            cpu_count = (
                os.cpu_count()
                or 1
            )

            cpu = (
                load
                / cpu_count
                * 100
            )

            cpu = max(
                0.0,
                min(100.0, cpu)
            )

        except Exception:

            cpu = 0.0

        return {
            "cpu_percent": round(
                cpu,
                2
            ),

            "ram_percent": 0.0
        }


# ============================================================
# GOSSIP MESSAGE
# ============================================================

class GossipMessage:

    def __init__(
        self,
        sender_id,
        cpu_percent,
        ram_percent
    ):

        self.message_id = str(
            uuid.uuid4()
        )

        self.sender_id = str(
            sender_id
        )

        self.message_type = (
            MESSAGE_TYPE
        )

        self.cpu_percent = float(
            cpu_percent
        )

        self.ram_percent = float(
            ram_percent
        )

        self.timestamp = time.time()

    # --------------------------------------------------------
    # SERIALIZE
    # --------------------------------------------------------

    def to_dict(self):

        return {
            "message_id":
                self.message_id,

            "sender_id":
                self.sender_id,

            "message_type":
                self.message_type,

            "cpu_percent":
                self.cpu_percent,

            "ram_percent":
                self.ram_percent,

            "timestamp":
                self.timestamp
        }

    # --------------------------------------------------------
    # DESERIALIZE
    # --------------------------------------------------------

    @classmethod
    def from_dict(
        cls,
        data
    ):

        message = cls(
            sender_id=data[
                "sender_id"
            ],

            cpu_percent=data[
                "cpu_percent"
            ],

            ram_percent=data[
                "ram_percent"
            ]
        )

        message.message_id = data.get(
            "message_id",
            str(uuid.uuid4())
        )

        message.timestamp = float(
            data.get(
                "timestamp",
                time.time()
            )
        )

        return message


